CREATE TABLE NOTIFICACION_ENVIO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EVENTO VARCHAR(100) NOT NULL,
    ID_TRANSACCION VARCHAR(100),
    EVENTO_JSON TEXT NOT NULL,
    DESTINATARIO VARCHAR(320) NOT NULL,
    ASUNTO VARCHAR(500) NOT NULL,
    CONTENIDO_HTML TEXT,
    RUTA_XML_AUTORIZADO VARCHAR(1000) NOT NULL,
    RUTA_RIDE VARCHAR(1000) NOT NULL,
    ESTADO_ENVIO VARCHAR(20) NOT NULL,
    NUMERO_INTENTOS INTEGER NOT NULL DEFAULT 0,
    FECHA_RECEPCION TIMESTAMPTZ NOT NULL,
    FECHA_ENVIO TIMESTAMPTZ,
    RESPUESTA_ENVIO TEXT,
    FECHA_CREACION TIMESTAMPTZ NOT NULL,
    FECHA_MODIFICACION TIMESTAMPTZ NOT NULL,
    CONSTRAINT UK_NOTIFICACION_ENVIO_EVENTO UNIQUE (ID_EVENTO),
    CONSTRAINT CK_NOTIFICACION_ENVIO_ESTADO
        CHECK (ESTADO_ENVIO IN ('PENDIENTE', 'EN_PROCESO', 'ENVIADA', 'FALLIDA')),
    CONSTRAINT CK_NOTIFICACION_ENVIO_INTENTOS CHECK (NUMERO_INTENTOS >= 0)
);

CREATE INDEX IDX_NOTIFICACION_ENVIO_ESTADO_RECEPCION
    ON NOTIFICACION_ENVIO (ESTADO_ENVIO, FECHA_RECEPCION);
